    #[test]
    fn counters_stay_within_their_limits() {
        let (_root, store) = store();
        store.create("agent", new_task("first"), None).unwrap();
        let dir = store.dir().to_owned();
        let at_limit = edit(&dir, "T-1.json", "revision", json!(REVISION_MAX));
        let refused = store.update("agent", "T-1", REVISION_MAX, doing(), None).unwrap_err();
        assert!(matches!(&refused, TaskError::Invalid(m) if m.contains("the highest a task can reach")), "{refused}");
        assert_eq!(file_bytes(&store, "T-1.json"), at_limit);
        edit(&dir, "T-1.json", "revision", json!(REVISION_MAX + 1));
        assert!(matches!(store.get("T-1"), Err(TaskError::Unreadable { .. })));
        edit(&dir, "T-1.json", "revision", json!(1));

        // Names above the id limit are unreadable, but still hold their ids.
        for name in ["T-1000000001.json", "T-99999999999999999999999.json"] {
            fs::write(dir.join(name), "{}").unwrap();
            let refused = store.create("agent", new_task("next"), None).unwrap_err();
            assert!(refused.to_string().contains(&format!("no task id is left: {name}")), "{refused}");
            let page = store.list(&TaskFilter::default(), 0, 10).unwrap();
            assert!(page.unreadable.iter().any(|u| u.file == name && u.error.contains("above the limit")), "{page:?}");
            fs::remove_file(dir.join(name)).unwrap();
        }
        assert!(matches!(store.get("T-1000000001"), Err(TaskError::Invalid(_))));
        // The last id is a valid task, and nothing comes after it.
        fs::copy(dir.join("T-1.json"), dir.join("T-1000000000.json")).unwrap();
        edit(&dir, "T-1000000000.json", "id", json!("T-1000000000"));
        assert_eq!(store.get("T-1000000000").unwrap().title, "first");
        let refused = store.create("agent", new_task("next"), None).unwrap_err();
        assert!(refused.to_string().contains("T-1000000000.json holds an id"), "{refused}");
    }

    #[test]
    fn loaded_records_are_validated_like_writes_and_never_rewritten() {
        let (_root, store) = store();
        store.create("agent", new_task("valid"), None).unwrap();
        let good: serde_json::Value = serde_json::from_slice(&file_bytes(&store, "T-1.json")).unwrap();
        let entry = |field: &str, value: serde_json::Value| {
            let mut entry = good["log"][0].clone();
            entry[field] = value;
            entry
        };
        let receipt = |hash: serde_json::Value| {
            let mut entry = entry("mutation_id", json!("m-1"));
            entry["mutation_hash"] = hash;
            entry
        };
        let cases = [
            ("title", json!("x".repeat(TITLE_MAX_CHARS + 1)), "title is 201 characters"),
            ("request", json!(" \n"), "request must not be empty"),
            ("source", json!(""), "source must not be empty"),
            ("owner", json!(""), "owner must not be empty"),
            ("evidence", json!(["a", "a"]), "same link twice"),
            ("parent", json!("T-0"), "parent is not a task id"),
            ("revision", json!(0), "revision 0"),
            ("created_at", json!("today"), "created_at is not an RFC 3339 time"),
            ("log", json!([]), "\"created\" entry"),
            ("log", json!([entry("what", json!("note"))]), "\"created\" entry"),
            ("log", json!([entry("at", json!("yesterday"))]), "a log time"),
            ("log", json!([receipt(json!(null))]), "mutation id without its hash"),
            ("log", json!([receipt(json!("not a digest"))]), "not a SHA-256 hex digest"),
        ];
        let mut written = Vec::new();
        for (n, (field, value, expected)) in cases.into_iter().enumerate() {
            let id = task_id(n as u64 + 2);
            let mut task = good.clone();
            task["id"] = json!(id);
            task[field] = value;
            let bytes = serde_json::to_vec_pretty(&task).unwrap();
            fs::write(store.dir().join(file_name(n as u64 + 2)), &bytes).unwrap();
            written.push((id, bytes, expected));
        }
        let page = store.list(&TaskFilter::default(), 0, 100).unwrap();
        assert_eq!((page.total, page.unreadable.len()), (1, written.len()));
        for (unreadable, (id, bytes, expected)) in page.unreadable.iter().zip(&written) {
            assert!(unreadable.error.contains(expected), "{}: {}", unreadable.file, unreadable.error);
            assert!(matches!(store.update("agent", id, 1, doing(), None), Err(TaskError::Unreadable { .. })));
            assert_eq!(&file_bytes(&store, &unreadable.file), bytes, "{id} changed");
        }
    }

