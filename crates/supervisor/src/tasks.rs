//! Agent-managed task store: one pretty-printed JSON file per task (`T-<n>.json`)
//! in a folder PRIM-1 is pointed at, often a git repository. One runtime owns a
//! folder at a time (OS lock on `.prim1-tasks.lock`). Mutations are serialized,
//! revision-checked, and commit the record with its log entry in one atomic file
//! replacement. `request` and `source` are fixed at create; there is no delete.
//! Files on disk are untrusted: a record that does not validate is reported and
//! never rewritten. Mutation ids are checked against the receipts in the files
//! themselves, never only against memory. Atomic replacement does not make a
//! concurrent git operation transactional, and this is a workflow rule, not a
//! same-user security boundary.
//! Every call does blocking file I/O; keep it off UI and terminal-output threads.
use std::{
    collections::{HashMap, HashSet, hash_map::Entry},
    fmt,
    fs::{self, File, OpenOptions},
    io::{Read as _, Write as _},
    path::{Path, PathBuf},
};

use chrono::{SecondsFormat, Utc};
use parking_lot::Mutex;
use serde::{Deserialize, Deserializer, Serialize};
use sha2::{Digest, Sha256};
use uuid::Uuid;

pub const TASK_SCHEMA_VERSION: u32 = 1;
pub const LIST_MAX_LIMIT: usize = 200;
pub const LOCK_FILE_NAME: &str = ".prim1-tasks.lock";
const TITLE_MAX_CHARS: usize = 200;
// Actor, owner and reviewer identities.
const NAME_MAX_CHARS: usize = 200;
const MUTATION_ID_MAX_CHARS: usize = 128;
const REQUEST_MAX_BYTES: usize = 64 * 1024;
// Source, outcome and note.
const TEXT_MAX_BYTES: usize = 8 * 1024;
const EVIDENCE_MAX_COUNT: usize = 50;
const EVIDENCE_MAX_BYTES: usize = 1024;
// Whole-file cap on read and write; the log grows with every update.
const RECORD_MAX_BYTES: usize = 1024 * 1024;
// Counters stop far below u64::MAX, so a value read from disk can never
// overflow; a larger id or revision on disk makes its file unreadable.
const ID_MAX: u64 = 1_000_000_000;
const REVISION_MAX: u64 = 1_000_000_000;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum TaskState {
    Open,
    Doing,
    Blocked,
    Review,
    Done,
    /// Replaces deletion: the record stays, out of the active work.
    Dropped,
}

impl fmt::Display for TaskState {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Open => "open",
            Self::Doing => "doing",
            Self::Blocked => "blocked",
            Self::Review => "review",
            Self::Done => "done",
            Self::Dropped => "dropped",
        })
    }
}

/// The file format. Unknown fields make a file unreadable, so a rewrite can
/// never silently drop data written by a newer or hand-edited record.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Task {
    pub schema_version: u32,
    pub id: String,
    pub title: String,
    /// The original words, verbatim. No operation changes them after create.
    pub request: String,
    /// Where the request came from (room and time, or a file path).
    pub source: String,
    /// What done means.
    pub outcome: String,
    pub state: TaskState,
    pub owner: Option<String>,
    pub reviewer: Option<String>,
    pub parent: Option<String>,
    pub evidence: Vec<String>,
    pub created_at: String,
    pub updated_at: String,
    pub revision: u64,
    pub log: Vec<LogEntry>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LogEntry {
    pub at: String,
    /// Identity supplied by the calling layer, never free text from the agent.
    pub by: String,
    /// Change summary generated by the store.
    pub what: String,
    /// The caller's own words for this change, kept apart from `what`.
    pub note: Option<String>,
    pub mutation_id: Option<String>,
    pub mutation_hash: Option<String>,
}

/// Absent optional fields are not serialized, so adding a field later leaves
/// the mutation hash of earlier requests unchanged.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NewTask {
    pub title: String,
    pub request: String,
    pub source: String,
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub outcome: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub owner: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reviewer: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub evidence: Vec<String>,
}

/// `None` leaves a field unchanged. For owner, reviewer and parent, `Some(None)`
/// (JSON `null`) clears it. There is deliberately no request or source field.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TaskPatch {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub state: Option<TaskState>,
    #[serde(default, skip_serializing_if = "Option::is_none", deserialize_with = "present")]
    pub owner: Option<Option<String>>,
    #[serde(default, skip_serializing_if = "Option::is_none", deserialize_with = "present")]
    pub reviewer: Option<Option<String>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub outcome: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none", deserialize_with = "present")]
    pub parent: Option<Option<String>>,
    /// Evidence is a set: a link already on the task changes nothing.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub add_evidence: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
}

// A present field, even `null`, is a change; a missing one defaults to `None`.
fn present<'de, D: Deserializer<'de>>(d: D) -> Result<Option<Option<String>>, D::Error> {
    Option::<String>::deserialize(d).map(Some)
}

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct TaskFilter {
    pub state: Option<TaskState>,
    pub owner: Option<String>,
    pub parent: Option<String>,
}

impl TaskFilter {
    fn matches(&self, task: &Task) -> bool {
        self.state.is_none_or(|state| state == task.state)
            && self.owner.as_ref().is_none_or(|owner| task.owner.as_ref() == Some(owner))
            && self.parent.as_ref().is_none_or(|parent| task.parent.as_ref() == Some(parent))
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct TaskPage {
    pub items: Vec<Task>,
    /// Readable tasks matching the filter, before paging.
    pub total: usize,
    /// Every task file that cannot be used, regardless of filter and page.
    pub unreadable: Vec<UnreadableFile>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct UnreadableFile {
    pub file: String,
    pub error: String,
}

/// Messages are read by agents: each says what happened and what to do next.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum TaskError {
    StoreOwned,
    NotFound(String),
    Conflict { current_revision: u64 },
    MutationReused { mutation_id: String },
    /// The files cannot confirm what an earlier use of this mutation id did.
    MutationUnconfirmed { mutation_id: String, reason: String },
    Unreadable { file: String, error: String },
    Invalid(String),
    Io(String),
}

impl fmt::Display for TaskError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::StoreOwned => f.write_str(
                "this task folder is already open in another PRIM-1 runtime; close that runtime or choose a different folder",
            ),
            Self::NotFound(id) => write!(f, "task {id} does not exist"),
            Self::Conflict { current_revision } => write!(
                f,
                "the task changed since you read it and is now at revision {current_revision}; read it again and reapply your change against that revision",
            ),
            Self::MutationReused { mutation_id } => write!(
                f,
                "mutation id {mutation_id} was already used for a different change; use a new mutation id for a new change",
            ),
            Self::MutationUnconfirmed { mutation_id, reason } => {
                write!(f, "mutation id {mutation_id} was refused and nothing was written: {reason}")
            }
            Self::Unreadable { file, error } => write!(
                f,
                "task file {file} cannot be used: {error}. It was left untouched; fix or restore it (for example in git) first",
            ),
            Self::Invalid(message) => f.write_str(message),
            Self::Io(message) => write!(f, "task storage failed: {message}"),
        }
    }
}

impl std::error::Error for TaskError {}

pub struct TaskStore {
    dir: PathBuf,
    state: Mutex<StoreState>,
    // Held for the store's lifetime; dropping it releases the folder.
    _lock: File,
}

struct StoreState {
    // Highest id seen at open or handed out since; never handed out again.
    highest: u64,
    // Mutation id -> its receipt in the logs. Only a cache: a miss rescans
    // every file, and a hit is checked against its file before a replay.
    receipts: HashMap<String, Receipt>,
}

#[derive(PartialEq)]
enum Receipt {
    At { task: String, hash: String },
    // Recorded more than once, or not where it was before: the tasks involved.
    Conflict(Vec<String>),
}

// Hashed with SHA-256 because the hash is persisted and compared across
// restarts and toolchains; std's DefaultHasher is not stable between releases.
#[derive(Serialize)]
#[serde(tag = "op", rename_all = "lowercase")]
enum MutationInput<'a> {
    Create { actor: &'a str, task: &'a NewTask },
    Update { actor: &'a str, id: &'a str, expected_revision: u64, patch: &'a TaskPatch },
}

impl MutationInput<'_> {
    fn hash(&self) -> String {
        let bytes = serde_json::to_vec(self).expect("task mutation input serializes");
        format!("{:x}", Sha256::digest(bytes))
    }
}

enum ReadFailure {
    Missing,
    Unreadable(String),
}

impl TaskStore {
    /// Creates the folder if needed and takes its writer lock; a folder owned by
    /// a live store (in any process) returns `StoreOwned`.
    pub fn open(dir: &Path) -> Result<TaskStore, TaskError> {
        fs::create_dir_all(dir).map_err(|error| io_error("create the task folder", dir, error))?;
        let lock = acquire_lock(&dir.join(LOCK_FILE_NAME))?;
        let highest = scan(dir)?.into_iter().filter_map(|(number, _)| number).filter(|n| *n <= ID_MAX).max();
        let mut state = StoreState { highest: highest.unwrap_or(0), receipts: HashMap::new() };
        // Unreadable files stay out of the index; `replay` refuses any new
        // mutation id while one remains.
        rescan(dir, &mut state.receipts)?;
        Ok(TaskStore { dir: dir.to_path_buf(), state: Mutex::new(state), _lock: lock })
    }

    pub fn dir(&self) -> &Path {
        &self.dir
    }

    /// Reads from disk on every call. Items are ordered by numeric id; `limit`
    /// is capped at `LIST_MAX_LIMIT`.
    pub fn list(&self, filter: &TaskFilter, offset: usize, limit: usize) -> Result<TaskPage, TaskError> {
        let limit = limit.min(LIST_MAX_LIMIT);
        let (mut items, mut total, mut unreadable) = (Vec::new(), 0, Vec::new());
        for record in load_all(&self.dir)? {
            match record {
                Ok(task) if filter.matches(&task) => {
                    if total >= offset && items.len() < limit {
                        items.push(task);
                    }
                    total += 1;
                }
                Ok(_) => {}
                Err(file) => unreadable.push(file),
            }
        }
        Ok(TaskPage { items, total, unreadable })
    }

    pub fn get(&self, id: &str) -> Result<Task, TaskError> {
        self.read(parse_id(id)?)
    }

    pub fn create(&self, actor: &str, new: NewTask, mutation_id: Option<&str>) -> Result<Task, TaskError> {
        check_line("actor", actor, NAME_MAX_CHARS)?;
        check_mutation_id(mutation_id)?;
        check_content(&new.title, &new.request, &new.source, &new.outcome, &new.owner, &new.reviewer)?;
        let evidence = merge_evidence(&[], &new.evidence)?;
        let hash = mutation_id.map(|_| MutationInput::Create { actor, task: &new }.hash());

        let mut state = self.state.lock();
        if let Some(replayed) = self.replay(&mut state, mutation_id, hash.as_deref())? {
            return Ok(replayed);
        }
        let number = self.allocate(&state)?;
        let id = task_id(number);
        if let Some(parent) = &new.parent {
            self.check_parent(parent, &id)?;
        }
        let now = now();
        let task = Task {
            schema_version: TASK_SCHEMA_VERSION,
            id,
            title: new.title,
            request: new.request,
            source: new.source,
            outcome: new.outcome,
            state: TaskState::Open,
            owner: new.owner,
            reviewer: new.reviewer,
            parent: new.parent,
            evidence,
            created_at: now.clone(),
            updated_at: now.clone(),
            revision: 1,
            log: vec![LogEntry {
                at: now,
                by: actor.to_owned(),
                what: "created".to_owned(),
                note: None,
                mutation_id: mutation_id.map(str::to_owned),
                mutation_hash: hash,
            }],
        };
        commit(&self.dir, &task, false)?;
        state.highest = number;
        remember(&mut state, &task);
        Ok(task)
    }

    /// Re-reads the record from disk and applies `patch` only if its revision is
    /// still `expected_revision`; otherwise returns `Conflict` without writing.
    pub fn update(
        &self,
        actor: &str,
        id: &str,
        expected_revision: u64,
        patch: TaskPatch,
        mutation_id: Option<&str>,
    ) -> Result<Task, TaskError> {
        check_line("actor", actor, NAME_MAX_CHARS)?;
        check_mutation_id(mutation_id)?;
        let number = parse_id(id)?;
        if let Some(title) = &patch.title {
            check_line("title", title, TITLE_MAX_CHARS)?;
        }
        if let Some(outcome) = &patch.outcome {
            check_bytes("outcome", outcome, TEXT_MAX_BYTES)?;
        }
        if let Some(note) = &patch.note {
            check_required("note", note, TEXT_MAX_BYTES)?;
        }
        check_names(&patch.owner.clone().flatten(), &patch.reviewer.clone().flatten())?;
        let hash = mutation_id
            .map(|_| MutationInput::Update { actor, id, expected_revision, patch: &patch }.hash());

        let mut state = self.state.lock();
        if let Some(replayed) = self.replay(&mut state, mutation_id, hash.as_deref())? {
            return Ok(replayed);
        }
        let mut task = self.read(number)?;
        if task.revision != expected_revision {
            return Err(TaskError::Conflict { current_revision: task.revision });
        }
        let revision = task.revision.checked_add(1).filter(|next| *next <= REVISION_MAX).ok_or_else(|| {
            TaskError::Invalid(format!(
                "{id} is at revision {}, the highest a task can reach; continue the work in a new task with parent {id}",
                task.revision,
                id = task.id
            ))
        })?;

        let mut changes = Vec::new();
        if let Some(title) = patch.title
            && title != task.title
        {
            changes.push(format!("title \"{}\" -> \"{title}\"", task.title));
            task.title = title;
        }
        if let Some(next) = patch.state
            && next != task.state
        {
            changes.push(format!("state {} -> {next}", task.state));
            task.state = next;
        }
        if let Some(owner) = patch.owner
            && owner != task.owner
        {
            changes.push(format!("owner {} -> {}", shown(&task.owner), shown(&owner)));
            task.owner = owner;
        }
        if let Some(reviewer) = patch.reviewer
            && reviewer != task.reviewer
        {
            changes.push(format!("reviewer {} -> {}", shown(&task.reviewer), shown(&reviewer)));
            task.reviewer = reviewer;
        }
        if let Some(outcome) = patch.outcome
            && outcome != task.outcome
        {
            changes.push("outcome rewritten".to_owned());
            task.outcome = outcome;
        }
        if let Some(parent) = patch.parent
            && parent != task.parent
        {
            if let Some(parent) = &parent {
                self.check_parent(parent, &task.id)?;
            }
            changes.push(format!("parent {} -> {}", shown(&task.parent), shown(&parent)));
            task.parent = parent;
        }
        let evidence = merge_evidence(&task.evidence, &patch.add_evidence)?;
        if evidence.len() > task.evidence.len() {
            changes.push(format!("added {} evidence", evidence.len() - task.evidence.len()));
            task.evidence = evidence;
        }
        if changes.is_empty() && patch.note.is_none() {
            return Err(TaskError::Invalid(format!(
                "nothing to change: {} already has these values; send at least one different field, new evidence or a note",
                task.id
            )));
        }

        let now = now();
        task.revision = revision;
        task.updated_at = now.clone();
        task.log.push(LogEntry {
            at: now,
            by: actor.to_owned(),
            what: if changes.is_empty() { "note".to_owned() } else { changes.join("; ") },
            note: patch.note,
            mutation_id: mutation_id.map(str::to_owned),
            mutation_hash: hash,
        });
        commit(&self.dir, &task, true)?;
        remember(&mut state, &task);
        Ok(task)
    }

    // `Some` replays a mutation id already applied: the task's current record,
    // only if its file still holds the receipt with this request's hash. A
    // different request is refused. Every mutation id is first reconciled
    // against all files, cached or not: an imported file can add a second
    // receipt for a known id, which makes its earlier result ambiguous. An id
    // no readable file holds is refused while any file cannot be read.
    // Nothing is written on any of these paths.
    fn replay(&self, state: &mut StoreState, mutation_id: Option<&str>, hash: Option<&str>) -> Result<Option<Task>, TaskError> {
        let (Some(mutation_id), Some(hash)) = (mutation_id, hash) else { return Ok(None) };
        let refuse = |reason: String| Err(TaskError::MutationUnconfirmed { mutation_id: mutation_id.to_owned(), reason });
        let unreadable = rescan(&self.dir, &mut state.receipts)?;
        if !state.receipts.contains_key(mutation_id) {
            if unreadable.is_empty() {
                return Ok(None);
            }
            let files = unreadable.iter().map(|u| format!("{} ({})", u.file, u.error)).collect::<Vec<_>>();
            return refuse(format!(
                "whether it was already applied cannot be checked while task files cannot be read: {}. Fix or restore them (for example in git), then retry with the same mutation id",
                files.join("; ")
            ));
        }
        let (task_id, recorded) = match &state.receipts[mutation_id] {
            Receipt::At { task, hash: recorded } => (task.clone(), recorded.clone()),
            Receipt::Conflict(tasks) => {
                return refuse(format!(
                    "the task files record it more than once or with different contents ({}), so its earlier result is ambiguous; send the change with a new mutation id",
                    tasks.join(", ")
                ));
            }
        };
        if recorded != hash {
            return Err(TaskError::MutationReused { mutation_id: mutation_id.to_owned() });
        }
        let gone = |detail: String| {
            refuse(format!(
                "it was applied to {task_id} earlier, but {detail} (for example it was reverted or restored); read {task_id} and, if the change is still wanted, send it with a new mutation id"
            ))
        };
        match self.get(&task_id) {
            Ok(task)
                if task.log.iter().any(|entry| {
                    entry.mutation_id.as_deref() == Some(mutation_id) && entry.mutation_hash.as_deref() == Some(hash)
                }) =>
            {
                Ok(Some(task))
            }
            Ok(_) => gone(format!("{task_id}.json no longer records it")),
            Err(TaskError::NotFound(_)) => gone(format!("{task_id}.json no longer exists")),
            Err(error) => Err(error),
        }
    }

    // One past the highest id any task file name holds or this runtime has
    // handed out. A name above ID_MAX holds its id too, so it exhausts the
    // range rather than being skipped.
    fn allocate(&self, state: &StoreState) -> Result<u64, TaskError> {
        let (mut highest, mut holder) = (state.highest, None);
        for (number, file) in scan(&self.dir)? {
            if let Some(number) = number
                && number > highest
            {
                (highest, holder) = (number, Some(file));
            }
        }
        highest.checked_add(1).filter(|next| *next <= ID_MAX).ok_or_else(|| {
            TaskError::Invalid(match holder {
                Some(file) => format!(
                    "no task id is left: {file} holds an id at or above the limit T-{ID_MAX}; rename or remove it if it is a mistake"
                ),
                None => format!("no task id is left: ids stop at T-{ID_MAX}"),
            })
        })
    }

    // Walks the whole ancestry `parent` would give `child`. Every ancestor must
    // exist and be readable, and the chain must end without reaching `child`
    // or repeating, so an imported or hand-edited parent cannot close a cycle.
    fn check_parent(&self, parent: &str, child: &str) -> Result<(), TaskError> {
        let invalid = |message: String| Err(TaskError::Invalid(message));
        let Ok(mut current) = parse_id(parent) else {
            return invalid(format!("parent {parent:?} is not a task id; task ids look like T-7"));
        };
        let mut seen = HashSet::new();
        loop {
            let id = task_id(current);
            if id == child {
                return invalid(format!("{parent} cannot be the parent of {child}: {child} would become its own ancestor"));
            }
            if !seen.insert(current) {
                return invalid(format!("parent {parent} cannot be used: its ancestors loop back to {id}; fix their parent fields first"));
            }
            let task = match self.read(current) {
                Ok(task) => task,
                Err(TaskError::NotFound(_)) if id == parent => return invalid(format!("parent {parent} does not exist")),
                Err(TaskError::NotFound(_)) => {
                    return invalid(format!("parent {parent} cannot be used: its ancestor {id} does not exist; fix the parent fields first"));
                }
                Err(error) => return Err(error),
            };
            // A malformed parent field already makes the record unreadable.
            match task.parent {
                Some(next) => current = parse_id(&next)?,
                None => return Ok(()),
            }
        }
    }

    fn read(&self, number: u64) -> Result<Task, TaskError> {
        read_record(&self.dir, number).map_err(|failure| match failure {
            ReadFailure::Missing => TaskError::NotFound(task_id(number)),
            ReadFailure::Unreadable(error) => TaskError::Unreadable { file: file_name(number), error },
        })
    }
}

// Indexes the receipt of the entry just committed; `replay` established that
// its mutation id was not recorded anywhere.
fn remember(state: &mut StoreState, task: &Task) {
    if let Some(LogEntry { mutation_id: Some(id), mutation_hash: Some(hash), .. }) = task.log.last() {
        state.receipts.insert(id.clone(), Receipt::At { task: task.id.clone(), hash: hash.clone() });
    }
}

// Reads every task file and adds its receipts to the index. A mutation id
// found twice, or not where the index already places it, becomes a conflict
// that is never replayed. Returns the files whose receipts are unknown.
fn rescan(dir: &Path, receipts: &mut HashMap<String, Receipt>) -> Result<Vec<UnreadableFile>, TaskError> {
    let (mut unreadable, mut seen) = (Vec::new(), HashSet::new());
    for record in load_all(dir)? {
        let task = match record {
            Ok(task) => task,
            Err(file) => {
                unreadable.push(file);
                continue;
            }
        };
        for entry in &task.log {
            let (Some(id), Some(hash)) = (&entry.mutation_id, &entry.mutation_hash) else { continue };
            let found = Receipt::At { task: task.id.clone(), hash: hash.clone() };
            let repeated = !seen.insert(id.clone());
            match receipts.entry(id.clone()) {
                Entry::Vacant(slot) => {
                    slot.insert(found);
                }
                Entry::Occupied(slot) if !repeated && *slot.get() == found => {}
                Entry::Occupied(mut slot) => {
                    let mut tasks = match slot.get() {
                        Receipt::At { task, .. } => vec![task.clone()],
                        Receipt::Conflict(tasks) => tasks.clone(),
                    };
                    if !tasks.contains(&task.id) {
                        tasks.push(task.id.clone());
                    }
                    slot.insert(Receipt::Conflict(tasks));
                }
            }
        }
    }
    Ok(unreadable)
}

fn now() -> String {
    Utc::now().to_rfc3339_opts(SecondsFormat::Millis, true)
}

fn task_id(number: u64) -> String {
    format!("T-{number}")
}

fn file_name(number: u64) -> String {
    format!("T-{number}.json")
}

// Canonical decimal only ("T-7", not "T-07"), so one task has one file name.
// Digits past u64 saturate: such a name still holds an id, above ID_MAX.
fn parse_number(digits: &str) -> Option<u64> {
    let canonical = !digits.is_empty()
        && !digits.starts_with('0')
        && digits.bytes().all(|byte| byte.is_ascii_digit());
    canonical.then(|| digits.parse().unwrap_or(u64::MAX))
}

fn parse_id(id: &str) -> Result<u64, TaskError> {
    id.strip_prefix("T-")
        .and_then(parse_number)
        .filter(|number| *number <= ID_MAX)
        .ok_or_else(|| TaskError::Invalid(format!("{id:?} is not a task id; task ids look like T-7, up to T-{ID_MAX}")))
}

fn shown(value: &Option<String>) -> &str {
    value.as_deref().unwrap_or("(none)")
}

// Every `T-*.json` entry, canonical ids first in numeric order, then any
// misnamed ones. Other files (the lock, temporaries, notes) are ignored.
fn scan(dir: &Path) -> Result<Vec<(Option<u64>, String)>, TaskError> {
    let entries = fs::read_dir(dir).map_err(|error| io_error("list the task folder", dir, error))?;
    let mut found = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|error| io_error("list the task folder", dir, error))?;
        let Ok(name) = entry.file_name().into_string() else { continue };
        if let Some(digits) = name.strip_prefix("T-").and_then(|rest| rest.strip_suffix(".json")) {
            found.push((parse_number(digits), name));
        }
    }
    found.sort_by(|a, b| (a.0.is_none(), a.0, &a.1).cmp(&(b.0.is_none(), b.0, &b.1)));
    Ok(found)
}

// Every task file in `scan` order: its record, or why it cannot be used.
// Files are read one at a time as the caller iterates, so a page or a rescan
// holds a single record in memory rather than the whole store.
fn load_all(dir: &Path) -> Result<impl Iterator<Item = Result<Task, UnreadableFile>> + '_, TaskError> {
    Ok(scan(dir)?.into_iter().filter_map(move |(number, file)| {
        let record = match number {
            None => Err("the name is not T-<number>.json".to_owned()),
            Some(number) if number > ID_MAX => Err(format!("its id is above the limit T-{ID_MAX}")),
            Some(number) => match read_record(dir, number) {
                Ok(task) => Ok(task),
                Err(ReadFailure::Missing) => return None,
                Err(ReadFailure::Unreadable(error)) => Err(error),
            },
        };
        Some(record.map_err(|error| UnreadableFile { file, error }))
    }))
}

fn read_record(dir: &Path, number: u64) -> Result<Task, ReadFailure> {
    let unreadable = |error: String| Err(ReadFailure::Unreadable(error));
    let mut bytes = Vec::new();
    match File::open(dir.join(file_name(number))) {
        Ok(file) => {
            if let Err(error) = file.take(RECORD_MAX_BYTES as u64 + 1).read_to_end(&mut bytes) {
                return unreadable(format!("it cannot be read ({error})"));
            }
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Err(ReadFailure::Missing),
        Err(error) => return unreadable(format!("it cannot be opened ({error})")),
    }
    if bytes.len() > RECORD_MAX_BYTES {
        return unreadable("it is larger than the 1 MiB record limit".to_owned());
    }
    let Ok(text) = String::from_utf8(bytes) else {
        return unreadable("it is not UTF-8 text".to_owned());
    };
    if text.lines().any(|line| {
        ["<<<<<<<", ">>>>>>>", "|||||||"].iter().any(|marker| line.starts_with(marker)) || line == "======="
    }) {
        return unreadable("it contains git merge conflict markers; resolve the conflict in git".to_owned());
    }
    #[derive(Deserialize)]
    struct Probe {
        schema_version: Option<serde_json::Value>,
    }
    let probe: Probe = match serde_json::from_str(&text) {
        Ok(probe) => probe,
        Err(error) => return unreadable(format!("it is not a JSON task object ({error})")),
    };
    if probe.schema_version.as_ref().and_then(serde_json::Value::as_u64) != Some(TASK_SCHEMA_VERSION.into()) {
        let found = probe.schema_version.map_or("no schema_version".to_owned(), |v| format!("schema_version {v}"));
        return unreadable(format!("it has {found}; this PRIM-1 reads schema_version {TASK_SCHEMA_VERSION}"));
    }
    let task: Task = match serde_json::from_str(&text) {
        Ok(task) => task,
        Err(error) => return unreadable(format!("it does not match the task format ({error})")),
    };
    if task.id != task_id(number) {
        return unreadable(format!("it says it is {} but is stored as {}", task.id, file_name(number)));
    }
    if let Err(error) = check_record(&task) {
        return unreadable(format!("it is not a valid task record: {error}"));
    }
    Ok(task)
}

// What every record read from disk must satisfy: the field rules of create
// and update, plus a log that starts with the creation and well-formed
// receipts. Values are not echoed, since a file may hold up to 1 MiB.
fn check_record(task: &Task) -> Result<(), TaskError> {
    let invalid = |message: &str| Err(TaskError::Invalid(message.to_owned()));
    if !(1..=REVISION_MAX).contains(&task.revision) {
        return invalid(&format!("revision {} is outside 1 to {REVISION_MAX}", task.revision));
    }
    check_content(&task.title, &task.request, &task.source, &task.outcome, &task.owner, &task.reviewer)?;
    if task.parent.as_deref().is_some_and(|parent| parse_id(parent).is_err()) {
        return invalid("parent is not a task id");
    }
    if merge_evidence(&[], &task.evidence)? != task.evidence {
        return invalid("evidence lists the same link twice");
    }
    check_time("created_at", &task.created_at)?;
    check_time("updated_at", &task.updated_at)?;
    if task.log.first().is_none_or(|entry| entry.what != "created") {
        return invalid("the log does not start with the \"created\" entry");
    }
    for entry in &task.log {
        check_time("a log time", &entry.at)?;
        check_line("a log actor", &entry.by, NAME_MAX_CHARS)?;
        check_required("a log change", &entry.what, TEXT_MAX_BYTES)?;
        if let Some(note) = &entry.note {
            check_required("a log note", note, TEXT_MAX_BYTES)?;
        }
        match (&entry.mutation_id, &entry.mutation_hash) {
            (None, None) => {}
            (Some(id), Some(hash)) => {
                check_mutation_id(Some(id))?;
                if hash.len() != 64 || !hash.bytes().all(|byte| matches!(byte, b'0'..=b'9' | b'a'..=b'f')) {
                    return invalid("a log receipt hash is not a SHA-256 hex digest");
                }
            }
            _ => return invalid("a log entry has a mutation id without its hash, or a hash without its id"),
        }
    }
    Ok(())
}

fn check_time(field: &str, value: &str) -> Result<(), TaskError> {
    chrono::DateTime::parse_from_rfc3339(value)
        .map(drop)
        .map_err(|_| TaskError::Invalid(format!("{field} is not an RFC 3339 time")))
}

// Same commit pattern as `persist_catalog`: unique temporary file in the same
// folder, write, flush, sync, then one rename. The temporary keeps the folder's
// inherited permissions (unlike runtime catalogs) because the folder is the
// user's own, often a repository. Creation never replaces an existing name.
fn commit(dir: &Path, task: &Task, replace: bool) -> Result<(), TaskError> {
    let mut bytes = serde_json::to_vec_pretty(task)
        .map_err(|error| TaskError::Io(format!("cannot encode {} ({error})", task.id)))?;
    bytes.push(b'\n');
    if bytes.len() > RECORD_MAX_BYTES {
        return Err(TaskError::Invalid(format!(
            "{id} would grow past the 1 MiB record limit; continue the work in a new task with parent {id}",
            id = task.id
        )));
    }
    let name = format!("{}.json", task.id);
    let destination = dir.join(&name);
    let temporary = dir.join(format!(".{name}.{}.tmp", Uuid::new_v4()));
    let result = (|| -> Result<(), TaskError> {
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temporary)
            .map_err(|error| io_error("create a temporary task file", &temporary, error))?;
        file.write_all(&bytes)
            .and_then(|()| file.flush())
            .and_then(|()| file.sync_all())
            .map_err(|error| io_error("write a temporary task file", &temporary, error))?;
        drop(file);
        if replace {
            crate::replace_catalog_file(&temporary, &destination, "task record")
                .map_err(|error| TaskError::Io(format!("{error:#}")))
        } else {
            install_new(&temporary, &destination).map_err(|error| match error.kind() {
                std::io::ErrorKind::AlreadyExists => TaskError::Io(format!(
                    "{name} appeared in the task folder while it was being created; try again"
                )),
                _ => io_error("install the new task file", &destination, error),
            })
        }
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    result
}

#[cfg(windows)]
fn install_new(temporary: &Path, destination: &Path) -> std::io::Result<()> {
    use std::os::windows::ffi::OsStrExt as _;
    use windows_sys::Win32::Storage::FileSystem::{MOVEFILE_WRITE_THROUGH, MoveFileExW};

    let wide = |path: &Path| path.as_os_str().encode_wide().chain(Some(0)).collect::<Vec<_>>();
    let (from, to) = (wide(temporary), wide(destination));
    // Without MOVEFILE_REPLACE_EXISTING the move fails when the name is taken.
    if unsafe { MoveFileExW(from.as_ptr(), to.as_ptr(), MOVEFILE_WRITE_THROUGH) } == 0 {
        return Err(std::io::Error::last_os_error());
    }
    Ok(())
}

#[cfg(not(windows))]
fn install_new(temporary: &Path, destination: &Path) -> std::io::Result<()> {
    // link(2) refuses an existing name; the temporary name is then dropped.
    fs::hard_link(temporary, destination)?;
    let _ = fs::remove_file(temporary);
    Ok(())
}

#[cfg(windows)]
fn acquire_lock(path: &Path) -> Result<File, TaskError> {
    use std::os::windows::fs::OpenOptionsExt as _;
    use windows_sys::Win32::{
        Foundation::ERROR_SHARING_VIOLATION,
        Storage::FileSystem::{DELETE, FILE_FLAG_DELETE_ON_CLOSE, FILE_GENERIC_READ, FILE_GENERIC_WRITE},
    };

    // No sharing: any second open, in any process, fails while this handle
    // lives. Delete-on-close keeps the lock file out of the folder (and out of
    // `git status`) whenever no runtime owns it, including after a crash.
    OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .access_mode(FILE_GENERIC_READ | FILE_GENERIC_WRITE | DELETE)
        .share_mode(0)
        .custom_flags(FILE_FLAG_DELETE_ON_CLOSE)
        .open(path)
        .map_err(|error| match error.raw_os_error() {
            Some(code) if code == ERROR_SHARING_VIOLATION as i32 => TaskError::StoreOwned,
            _ => io_error("lock the task folder", path, error),
        })
}

#[cfg(not(windows))]
fn acquire_lock(path: &Path) -> Result<File, TaskError> {
    use std::os::fd::AsRawFd as _;

    let file = OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .open(path)
        .map_err(|error| io_error("lock the task folder", path, error))?;
    // flock is per open file description, so a second open in this process is
    // refused as well. The file stays; unlinking it would race a new owner.
    if unsafe { libc::flock(file.as_raw_fd(), libc::LOCK_EX | libc::LOCK_NB) } != 0 {
        let error = std::io::Error::last_os_error();
        return Err(match error.kind() {
            std::io::ErrorKind::WouldBlock => TaskError::StoreOwned,
            _ => io_error("lock the task folder", path, error),
        });
    }
    Ok(file)
}

fn io_error(action: &str, path: &Path, error: std::io::Error) -> TaskError {
    TaskError::Io(format!("could not {action} {} ({error})", path.display()))
}

fn check_mutation_id(mutation_id: Option<&str>) -> Result<(), TaskError> {
    mutation_id.map_or(Ok(()), |id| check_line("mutation id", id, MUTATION_ID_MAX_CHARS))
}

// Field rules shared by create and by every record read from disk.
fn check_content(
    title: &str,
    request: &str,
    source: &str,
    outcome: &str,
    owner: &Option<String>,
    reviewer: &Option<String>,
) -> Result<(), TaskError> {
    check_line("title", title, TITLE_MAX_CHARS)?;
    check_required("request", request, REQUEST_MAX_BYTES)?;
    check_required("source", source, TEXT_MAX_BYTES)?;
    check_bytes("outcome", outcome, TEXT_MAX_BYTES)?;
    check_names(owner, reviewer)
}

fn check_names(owner: &Option<String>, reviewer: &Option<String>) -> Result<(), TaskError> {
    for (field, value) in [("owner", owner), ("reviewer", reviewer)] {
        if let Some(value) = value {
            check_line(field, value, NAME_MAX_CHARS)?;
        }
    }
    Ok(())
}

// One non-blank line of at most `max_chars` characters.
fn check_line(field: &str, value: &str, max_chars: usize) -> Result<(), TaskError> {
    let invalid = |message: String| Err(TaskError::Invalid(message));
    if value.trim().is_empty() {
        return invalid(format!("{field} must not be empty"));
    }
    if value.contains(['\n', '\r']) {
        return invalid(format!("{field} must be a single line"));
    }
    let chars = value.chars().count();
    if chars > max_chars {
        return invalid(format!("{field} is {chars} characters; the limit is {max_chars}"));
    }
    Ok(())
}

fn check_required(field: &str, value: &str, max_bytes: usize) -> Result<(), TaskError> {
    if value.trim().is_empty() {
        return Err(TaskError::Invalid(format!("{field} must not be empty")));
    }
    check_bytes(field, value, max_bytes)
}

fn check_bytes(field: &str, value: &str, max_bytes: usize) -> Result<(), TaskError> {
    if value.len() > max_bytes {
        return Err(TaskError::Invalid(format!(
            "{field} is {} bytes; the limit is {} KiB ({max_bytes} bytes)",
            value.len(),
            max_bytes / 1024
        )));
    }
    Ok(())
}

// Existing evidence plus new, distinct, non-blank links of at most 1 KiB each.
fn merge_evidence(existing: &[String], added: &[String]) -> Result<Vec<String>, TaskError> {
    let mut evidence = existing.to_vec();
    for link in added {
        check_required("evidence", link, EVIDENCE_MAX_BYTES)?;
        if !evidence.contains(link) {
            evidence.push(link.clone());
        }
    }
    if evidence.len() > EVIDENCE_MAX_COUNT {
        return Err(TaskError::Invalid(format!(
            "a task holds at most {EVIDENCE_MAX_COUNT} evidence entries, not {}",
            evidence.len()
        )));
    }
    Ok(evidence)
}

