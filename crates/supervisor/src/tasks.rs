        task.log.push(filler.clone());
        let one = size(&task);
        task.log.push(filler.clone());
        let step = size(&task) - one;
        task.log.extend(std::iter::repeat_n(filler, (RECORD_MAX_BYTES - one) / step - 1));
        task.revision = task.log.len() as u64;
